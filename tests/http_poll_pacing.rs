/// A response whose body arrives in two windows: the header poll's consume-once
/// stash must not end the stream, and each window must reach `data` in order.
/// A canned server on a Rust thread is the only way to stream here — the
/// runtime's own `ServerResponse` aggregates its body before it answers — and
/// the body is sent **chunked**, because the transport surfaces
/// `Content-Length` bodies only once complete while chunked frames reach a poll
/// window as they arrive (measured).
#[tokio::test(flavor = "current_thread")]
async fn streamed_body_windows_arrive_in_order() {
    let listener = TcpListener::bind("127.0.0.1:0").expect("bind loopback");
    let port = listener.local_addr().expect("local addr").port();
    std::thread::spawn(move || {
        for stream in listener.incoming().flatten() {
            let mut stream: TcpStream = stream;
            let mut buffer = [0u8; 4096];
            let _ = stream.read(&mut buffer);
            let _ = stream
                .write_all(b"HTTP/1.1 200 OK\r\ntransfer-encoding: chunked\r\n\r\n5\r\nfirst\r\n");
            let _ = stream.flush();
            std::thread::sleep(std::time::Duration::from_millis(300));
            let _ = stream.write_all(b"6\r\n-again\r\n0\r\n\r\n");
            let _ = stream.flush();
        }
    });
    let ts = format!(
        r#"
import http from "node:http";

export default (pi) => {{
  pi.on("session_start", async () => {{
    const out = {{ chunks: [], events: [] }};
    await new Promise(function (resolve) {{
      http.get("http://127.0.0.1:{port}/stream", function (res) {{
        out.status = res.statusCode;
        res.on("data", function (chunk) {{ out.chunks.push(chunk.toString("utf8")); }});
        res.on("end", function () {{ out.events.push("end"); resolve(null); }});
      }}).on("error", function (error) {{
        out.events.push("error:" + error.code);
        resolve(null);
      }});
    }});
    out.body = out.chunks.join("");
    globalThis.__pirPaced = out;
  }});
}};
"#
    );
    let v = run_pacing_fixture("streamed", &ts).await;

    assert_eq!(v["status"], 200, "status: {v}");
    assert_eq!(
        v["events"],
        json!(["end"]),
        "the stream must end (never stall on the stashed window): {v}"
    );
    assert_eq!(
        v["chunks"],
        json!(["first", "-again"]),
        "each body window must arrive once, in order: {v}"
    );
    assert_eq!(v["body"], "first-again", "body reassembly: {v}");
}

// ---------------------------------------------------------------------------
// `fetchPoll`'s bounded wait: the response headers are reportable exactly once,
// and after that an empty poll must WAIT its `waitMs` slice for body progress
// instead of returning instantly on the mere existence of the headers. The
// pre-fix host broke its wait loop on `response.is_some()`, which is
// permanently true after the headers: every body poll became a zero-wait
// return, so the JS body pump spun (never yielding to the runtime's driver,
// freezing every host timer) whenever a consumer waited on a slow producer.
// ---------------------------------------------------------------------------

/// Peer that writes the response head immediately, then holds the 4-byte body
/// until the fixture asks for it with a second request to `/release`, and
/// closes. The body is released by an event (the fixture has already observed
/// the empty poll), not by a timer: "headers arrived, body has not" is no
/// longer a race against a sleep on a loaded box.
fn spawn_gated_body_server() -> u16 {
    use std::sync::{Condvar, Mutex};

    let listener = TcpListener::bind("127.0.0.1:0").expect("bind loopback");
    let port = listener.local_addr().expect("local addr").port();
    let gate = Arc::new((Mutex::new(false), Condvar::new()));
    std::thread::spawn(move || {
        for stream in listener.incoming().flatten() {
            let gate = Arc::clone(&gate);
            std::thread::spawn(move || {
                let mut stream: TcpStream = stream;
                let mut buffer = [0u8; 4096];
                let Ok(read) = stream.read(&mut buffer) else {
                    return;
                };
                let request = String::from_utf8_lossy(&buffer[..read]);
                if request.starts_with("GET /release") {
                    let (released, ready) = &*gate;
                    *released
                        .lock()
                        .unwrap_or_else(std::sync::PoisonError::into_inner) = true;
                    ready.notify_all();
                    let _ = stream.write_all(
                        b"HTTP/1.1 204 No Content\r\ncontent-length: 0\r\nconnection: close\r\n\r\n",
                    );
                    let _ = stream.flush();
                    return;
                }
                let _ = stream.write_all(
                    b"HTTP/1.1 200 OK\r\ncontent-length: 4\r\nconnection: close\r\n\r\n",
                );
                let _ = stream.flush();
                // Hold the body until the release request lands (bounded so a
                // dead fixture cannot leave this thread parked forever).
                let (released, ready) = &*gate;
                let mut released = released
                    .lock()
                    .unwrap_or_else(std::sync::PoisonError::into_inner);
                let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
                while !*released {
                    let remaining = deadline.saturating_duration_since(std::time::Instant::now());
                    if remaining.is_zero() {
                        break;
                    }
                    let (next, _) = ready
                        .wait_timeout(released, remaining)
                        .unwrap_or_else(std::sync::PoisonError::into_inner);
                    released = next;
                }
                drop(released);
                let _ = stream.write_all(b"pong");
                let _ = stream.flush();
            });
        }
    });
    port
}

/// The host poll window the fixture asks for (ms): the empty poll must consume
/// close to this slice instead of returning in ~0 ms.
const DELAYED_BODY_POLL_WAIT_MS: u64 = 30;
/// Lower bound on the empty poll's measured wait: a generous fraction of
/// [`DELAYED_BODY_POLL_WAIT_MS`] so a loaded box cannot flake it, while the
/// pre-fix zero-wait return (≤ a few ms) always fails it.
const DELAYED_BODY_MIN_WAIT_MS: u64 = 20;

#[tokio::test(flavor = "current_thread")]
async fn fetch_poll_waits_for_body_progress_after_headers() {
    let port = spawn_gated_body_server();
    let ts = format!(
        r#"
export default (pi) => {{
  pi.on("session_start", async () => {{
    const host = globalThis.__pir_host;
    const report = {{}};
    globalThis.__pirPaced = report;
    const started = JSON.parse(host.http("fetchStart", JSON.stringify({{
      url: "http://127.0.0.1:{port}/delayed",
    }})));
    const id = started.value.id;
    const poll = (waitMs) => JSON.parse(
      host.http("fetchPoll", JSON.stringify({{ id: id, waitMs: waitMs }}))
    ).value;
    // Poll until the headers are reported. `ready` is news exactly once, and
    // a loaded host can need more than one wait slice for the loopback
    // request to connect; the loop keeps the assertion about the report, not
    // about the box being fast.
    let headers = poll({wait});
    for (let attempt = 0; attempt < 200 && headers.ready !== true; attempt++) {{
      headers = poll({wait});
    }}
    report.ready = headers.ready;
    report.headersBody = headers.body;
    // Poll 2: the headers were already reported and the peer still holds the
    // body (it waits for /release), so this poll must WAIT its slice.
    const idleAt = Date.now();
    const idle = poll({wait});
    report.idleMs = Date.now() - idleAt;
    report.idleBody = idle.body;
    report.idleDone = idle.done;
    // Release the peer's body now that the empty poll has been observed.
    // Starting the request is enough; the poll loop below provides the time.
    const release = JSON.parse(host.http("fetchStart", JSON.stringify({{
      url: "http://127.0.0.1:{port}/release",
    }})));
    // Drain to the end (bounded): the body bytes arrive first and `done` after
    // the peer closes, so the drain loop must not assume one poll carries both.
    let bodyText = "";
    let done = false;
    let attempts = 0;
    while (!done && attempts < 200) {{
      const state = poll({wait});
      if (state.body) {{
        bodyText += Buffer.from(state.body, "base64").toString("utf8");
      }}
      done = state.done === true;
      attempts += 1;
    }}
    report.body = bodyText;
    report.done = done;
    host.http("fetchEnd", JSON.stringify({{ id: id }}));
    if (release.value && release.value.id !== undefined) {{
      host.http("fetchEnd", JSON.stringify({{ id: release.value.id }}));
    }}
  }});
}};
"#,
        port = port,
        wait = DELAYED_BODY_POLL_WAIT_MS,
    );
    let v = run_pacing_fixture("delayed-body", &ts).await;

    assert_eq!(
        v["ready"],
        json!(true),
        "the headers poll reports the response: {v}"
    );
    assert_eq!(
        v["idleBody"], "",
        "no body bytes are reported before the peer writes them: {v}"
    );
    assert_eq!(
        v["idleDone"], false,
        "the stream is not done while the peer still owes its body: {v}"
    );
    let idle_ms = v["idleMs"].as_u64().unwrap_or(0);
    assert!(
        idle_ms >= DELAYED_BODY_MIN_WAIT_MS,
        "an empty poll after the headers must wait its {DELAYED_BODY_POLL_WAIT_MS} ms slice \
         (waited {idle_ms} ms): {v}"
    );
    assert_eq!(
        v["body"], "pong",
        "the body arrives once the peer writes it: {v}"
    );
    assert_eq!(
        v["done"],
        json!(true),
        "the stream reports done at the end: {v}"
    );
}

// ---------------------------------------------------------------------------
// fetch body backpressure: a consumer that stops reading parks the host body
// reader, which closes the transport's window — delivery stops — and no byte
// is dropped once the consumer resumes.
//
// The invariant pinned here is "the bounded window bounds its PRODUCER (the
// reader's drain), and a stalled consumer loses nothing". Every witness is
// reader-side, because the window is a reader-side bound: the kernel can hold
// the whole surplus (measured on this host: the peer's single 24 MiB write
// returned in 11 ms), but nothing in it reaches the JS consumer until a
// `fetchPoll` drains the window. So the payload is 3× the window — enough that
// the window fills during the consumer's pause and the drain spans several
// window-sized batches — and the pause itself is what must gate the last byte.
// ---------------------------------------------------------------------------

/// The host's fetch response body window, mirrored from `MAX_STREAM_BYTES`
/// (`src/extensions/runtime/host_functions/http_fns.rs`): the bound every
/// assertion below is derived from.
const FETCH_WINDOW_BYTES: u64 = 8 * 1024 * 1024;

/// Bytes served to the fetch client: **three times** the window, so every byte
/// past the window must travel through the reader's drain (the kernel may keep
/// the surplus, but a poll is the only path into the consumer) and the drain
/// spans more than one window-sized batch.
const FETCH_BACKPRESSURE_BYTES: usize = 3 * FETCH_WINDOW_BYTES as usize;

/// Lower bound on the largest single delivery (`maxChunk`): half the window, so
/// "the stall let the window fill" is provable while leaving slack for a
/// stashed pre-stall window or a paced drain to be followed by the full one.
const FETCH_MIN_WINDOW_CHUNK_BYTES: u64 = FETCH_WINDOW_BYTES / 2;

/// The consumer's pause the fixture runs (ms), and the slack its witnesses get.
///
/// The pause is the fixture's own premise: `while (Date.now() < end) {}` with
/// `end = Date.now() + FETCH_STALL_MS`, so `stalledMs >= FETCH_STALL_MS` holds
/// up to millisecond rounding. The slack covers `Date.now()` granularity and
/// the store/serve bookkeeping between "the pause ended" and "the reader
/// observed the last byte"; the reader-side witness below is ~1.2 s wide, two
/// orders of magnitude past it.
const FETCH_STALL_MS: u64 = 1200;
const FETCH_STALL_SLACK_MS: u64 = 100;

/// Peer progress of one served connection, most-advanced-wins. Every step is
/// recorded so a stalled fetch names the leg that stalled: 1 = connection
/// accepted, 2 = request head read, 3 = response head written, 4 = body write
/// completed (the consumer drained the window), 5 = connection closed.
const PEER_ACCEPTED: u64 = 1;
const PEER_REQUEST_READ: u64 = 2;
const PEER_HEAD_WRITTEN: u64 = 3;
const PEER_BODY_WRITTEN: u64 = 4;
const PEER_CLOSED: u64 = 5;

/// The tuple returned by [`spawn_slow_consumer_server`]: `(port, write_ms,
/// peer_phase, peer_write_error)`.
type SlowConsumerServer = (
    u16,
    Arc<AtomicU64>,
    Arc<AtomicU64>,
    Arc<std::sync::Mutex<Option<String>>>,
);

/// Serve one request with a `content-length` body of
/// [`FETCH_BACKPRESSURE_BYTES`] bytes in a single `write_all`, recording how
/// long that write took.
///
/// The write time is a DIAGNOSTIC, not a witness: whether this write blocks
/// depends on how much surplus the loopback kernel can absorb (measured on
/// this host: all 16 MiB past the window, so the write returned in 11 ms). The
/// window bounds the READER — nothing reaches the consumer except through a
/// `fetchPoll` drain — which is what the fixture's reader-side witness asserts.
///
/// The write's `Result` is NOT discarded: a write that errors mid-body means
/// the client tore the connection down before the body was delivered — which
/// the fixture would otherwise see only as an unexplained stall or a short
/// byte count. The error text rides out so the test can name that cause
/// instead of misreading it as "the write was fast". Returns
/// `(port, write_ms, peer_phase, peer_write_error)`.
fn spawn_slow_consumer_server() -> SlowConsumerServer {
    let listener = TcpListener::bind("127.0.0.1:0").expect("bind loopback");
    let port = listener.local_addr().expect("local addr").port();
    let write_ms = Arc::new(AtomicU64::new(0));
    let recorded = Arc::clone(&write_ms);
    let phase = Arc::new(AtomicU64::new(0));
    let recorded_phase = Arc::clone(&phase);
    let write_error: Arc<std::sync::Mutex<Option<String>>> = Arc::default();
    let recorded_write_error = Arc::clone(&write_error);
    let step = move |value: u64| {
        // Monotonic: a retry/second connection must not hide how far the
        // stalled one got.
        recorded_phase.fetch_max(value, Ordering::SeqCst);
    };
    std::thread::spawn(move || {
        let body = vec![b'x'; FETCH_BACKPRESSURE_BYTES];
        for stream in listener.incoming().flatten() {
            let mut stream: TcpStream = stream;
            step(PEER_ACCEPTED);
            let mut buffer = [0u8; 4096];
            let _ = stream.read(&mut buffer);
            step(PEER_REQUEST_READ);
            let head = format!(
                "HTTP/1.1 200 OK\r\ncontent-length: {}\r\nconnection: close\r\n\r\n",
                body.len()
            );
            let started = std::time::Instant::now();
            let _ = stream.write_all(head.as_bytes());
            step(PEER_HEAD_WRITTEN);
            match stream.write_all(&body) {
                Ok(()) => {
                    let _ = stream.flush();
                    recorded.store(started.elapsed().as_millis() as u64, Ordering::SeqCst);
                    step(PEER_BODY_WRITTEN);
                }
                Err(error) => {
                    // The body never reached the wire in full: record WHY and
                    // do NOT advance the phase (a failed write is not "body
                    // written"). The fixture's byte count will be short; the
                    // assertion on this slot names the cause before anything
                    // else. A first-connection error only: a later benign close
                    // after a completed write never takes this arm.
                    if let Ok(mut slot) = recorded_write_error.lock() {
                        *slot = Some(error.to_string());
                    }
                }
            }
        }
        step(PEER_CLOSED);
    });
    (port, write_ms, phase, write_error)
}

#[tokio::test(flavor = "current_thread")]
async fn fetch_body_window_backpressures_without_losing_bytes() {
    let (port, write_ms, peer_phase, peer_write_error) = spawn_slow_consumer_server();
    let ts = r#"
export default (pi) => {
  pi.on("session_start", async () => {
    let report = { phase: "start", total: 0, chunks: 0, maxChunk: 0, contentLength: null,
                     firstByte: -1, lastByte: -1, stalledAt: 0, stalledMs: 0,
                     firstChunkAt: 0, doneAt: 0, error: null };
    // Publish EARLY and keep it current: if the dispatch dies on an engine
    // interrupt, this is the only record of where the fixture was.
    globalThis.__pirPaced = report;
    const response = await fetch("http://127.0.0.1:__PORT__/big");
    report.contentLength = response.headers.get("content-length");
    report.status = response.status;
    report.phase = "headers";
    // Stop reading, and block the JS thread so not even the poll loop runs:
    // the host's body window fills and the reader's drain is the only path the
    // remaining bytes could take. (The peer's write itself may have already
    // returned — a loopback kernel can hold the surplus — which is why the
    // witness for the window bound is READER-side, below.)
    report.stalledAt = Date.now();
    const end = report.stalledAt + __STALL__;
    while (Date.now() < end) { /* stall the consumer */ }
    report.stalledMs = Date.now() - report.stalledAt;
    report.phase = "stalled";
    // The read is bounded so a window that never drains reports its phase
    // (`read-timeout` + the byte count) instead of running into the 30 s
    // dispatch deadline, whose engine interrupt surfaces as an opaque
    // exception. A healthy drain never reaches the guard.
    let timedOut = false;
    const guard = new Promise((resolve) => setTimeout(() => { timedOut = true; resolve(null); }, 15000));
    try {
      const reader = response.body.getReader();
      for (;;) {
        const step = await Promise.race([reader.read(), guard]);
        if (timedOut || step === null || step.done) break;
        report.total += step.value.length;
        report.chunks += 1;
        if (report.firstChunkAt === 0) report.firstChunkAt = Date.now();
        if (step.value.length > report.maxChunk) report.maxChunk = step.value.length;
        if (report.firstByte < 0 && step.value.length > 0) report.firstByte = step.value[0];
        if (step.value.length > 0) report.lastByte = step.value[step.value.length - 1];
      }
      report.doneAt = Date.now();
      report.phase = timedOut ? "read-timeout" : "done";
    } catch (error) {
      report.phase = "read-error";
      report.error = String(error && error.message ? error.message : error);
    }
    globalThis.__pirPaced = report;
  });
};
"#
    .replace("__PORT__", &port.to_string())
    .replace("__STALL__", &FETCH_STALL_MS.to_string());
    // Inlined `run_pacing_fixture` (not the helper): the emit's failure report
    // must carry the PEER's progress as well as the fixture's — together they
    // separate "the request/response leg stalled" from "the body window never
    // drained" without a second run.
    let dir = write_temp_fixture("fetch-backpressure", &[("index.ts", &ts)]);
    let rt = ExtensionRuntime::new(test_config()).await.expect("runtime");
    rt.allow_root(dir.clone());
    let module = "pir-ext:fetch-backpressure.ts";
    rt.seed_module(module, &ts).expect("seed fixture");
    assert_eq!(
        rt.seeded_load(module).await.expect("seeded load"),
        1,
        "fixture must load"
    );
    let mut payload = json!({ "reason": "startup" });
    let outcome = match rt.emit("session_start", &mut payload).await {
        Ok(outcome) => outcome,
        Err(error) => {
            let progress = rt
                .eval_json("JSON.stringify(globalThis.__pirPaced ?? null)")
                .await
                .map(|value| value.to_string())
                .unwrap_or_else(|error| format!("<unreadable: {error}>"));
            panic!(
                "emit session_start failed: {error}; fixture progress: {progress}; peer phase: {} \
                 (1=accepted, 2=request read, 3=head written, 4=body written, 5=closed)",
                peer_phase.load(Ordering::SeqCst)
            );
        }
    };
    assert!(
        outcome.errors.is_empty(),
        "handler errors: {:?}",
        outcome.errors
    );
    let v: Value = rt
        .eval_json("JSON.stringify(globalThis.__pirPaced)")
        .await
        .expect("read fixture results");
    let _ = std::fs::remove_dir_all(&dir);

    assert_eq!(v["status"], 200, "status: {v}");
    // Cause before symptom: if the peer's single write errored mid-body, the
    // connection died before the body was delivered and the byte-integrity
    // assertions below would only show the symptom (a short count). The peer
    // never advances its phase on a failed write, so this is the first thing a
    // run reports when the transport — not the window protocol — is what broke.
    let write_error = peer_write_error
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
        .clone();
    assert!(
        write_error.is_none(),
        "the peer's single body write must not fail (a mid-body error means the \
         connection was torn down before the body was delivered): {write_error:?}; {v}"
    );
    assert_eq!(
        v["total"].as_u64(),
        Some(FETCH_BACKPRESSURE_BYTES as u64),
        "every byte arrives after the stall (nothing dropped): {v}"
    );
    assert_eq!(
        v["firstByte"].as_i64(),
        Some(b'x' as i64),
        "the first byte is the body's own byte: {v}"
    );
    assert_eq!(
        v["lastByte"].as_i64(),
        Some(b'x' as i64),
        "the last byte is the body's own byte: {v}"
    );
    assert_eq!(
        v["contentLength"].as_str(),
        Some(FETCH_BACKPRESSURE_BYTES.to_string().as_str()),
        "the headers still report the full length: {v}"
    );
    // INVARIANT, part 1 (window filled): a delivery of at least half the window
    // proves the host accumulated a window's worth while nobody read, i.e. the
    // consumer's pause really engaged the bound. With a 3× payload the window
    // is full for essentially the whole pause, so this is forced, not a race.
    let max_chunk = v["maxChunk"].as_u64().unwrap_or(0);
    assert!(
        max_chunk >= FETCH_MIN_WINDOW_CHUNK_BYTES,
        "the stall must let the {FETCH_WINDOW_BYTES}-byte window fill \
         (largest delivery {max_chunk} bytes): {v}"
    );
    // INVARIANT, part 2 (the pause is what gated delivery): the drain is the
    // only path from the transport into the consumer, so the last body byte
    // cannot arrive before the consumer resumes reading. The peer's own write
    // time is NOT asserted: the window is a READER-side bound, and a loopback
    // kernel can hold the whole surplus (measured on this host: the peer's
    // single 24 MiB write returned in ~11 ms, never blocking at all). The
    // fixture's pause is the gate, the last byte's timestamp is the witness,
    // and `write_ms` rides along in the message as a diagnostic only.
    let elapsed = write_ms.load(std::sync::atomic::Ordering::SeqCst);
    let stalled_ms = v["stalledMs"].as_u64().unwrap_or(0);
    assert!(
        stalled_ms + FETCH_STALL_SLACK_MS >= FETCH_STALL_MS,
        "the fixture's consumer pause must be real (measured {stalled_ms} ms of {FETCH_STALL_MS} ms): {v}"
    );
    let stalled_at = v["stalledAt"].as_u64().unwrap_or(0);
    let done_at = v["doneAt"].as_u64().unwrap_or(0);
    let observed_gate_ms = done_at.saturating_sub(stalled_at);
    assert!(
        observed_gate_ms >= stalled_ms.saturating_sub(FETCH_STALL_SLACK_MS),
        "the last body byte must arrive no earlier than the consumer's pause: the reader's stall is \
         what gated delivery (last byte at +{observed_gate_ms} ms, pause ended at +{stalled_ms} ms, \
         slack {FETCH_STALL_SLACK_MS} ms; peer's write took {elapsed} ms): {v}"
    );
}

// ---------------------------------------------------------------------------
// http.Server pending-request bound: more concurrent requests than the queue
// holds park the connection threads (backpressure) and every request is still
// dispatched exactly once and answered.
// ---------------------------------------------------------------------------

/// Concurrent requests driven at one server. Past the 256-request pending
/// queue (`MAX_PENDING_REQUESTS` in `http_fns.rs`), connection threads have to
/// park until `serverPoll` drains — so this count exercises the bound.
const SERVER_BOUND_REQUESTS: usize = 300;

#[tokio::test(flavor = "current_thread")]
#[ignore = "fixture uses 300 concurrent sockets, but MAX_SERVER_CONNECTIONS is 64; pending-queue bound is unreachable"]
async fn server_pending_queue_bounds_without_losing_requests() {
    let dir = write_temp_fixture("server-bound", &[]);
    let ts = r#"
import http from "node:http";
import fs from "node:fs";

const DIR = "__DIR__";
const PORT_FILE = DIR + "/port.txt";
const GO_FILE = DIR + "/go.txt";

export default (pi) => {
  pi.on("session_start", async () => {
    try { fs.unlinkSync(GO_FILE); } catch {}
    try { fs.unlinkSync(PORT_FILE); } catch {}
    const handled = [];
    let blockedMs = 0;
    const server = http.createServer((req, res) => {
      handled.push(req.url);
      res.writeHead(200, { "content-type": "text/plain" });
      res.end("path:" + req.url);
    });
    await new Promise((resolve) => server.listen(0, resolve));
    fs.writeFileSync(PORT_FILE, String(server.address().port));
    // Block the JS thread (and with it the server's pump) until the Rust side
    // has opened every connection: the requests pile up in the host's pending
    // queue, which parks the connection threads past its bound.
    const started = Date.now();
    const end = started + 10000;
    while (!fs.existsSync(GO_FILE) && Date.now() < end) {}
    blockedMs = Date.now() - started;
    // The pump resumes: it dispatches and answers the whole backlog.
    await new Promise((resolve) => setTimeout(resolve, 2500));
    const unique = new Set(handled).size;
    server.close();
    globalThis.__pirPaced = { handled: handled.length, unique, blockedMs };
  });
};
"#
    .replace("__DIR__", &dir.to_string_lossy().replace('\\', "/"));

    let rt = ExtensionRuntime::new(test_config()).await.expect("runtime");
    rt.allow_root(dir.clone());
    let module = "pir-ext:server-bound.ts";
    rt.seed_module(module, &ts).expect("seed fixture");
    assert_eq!(
        rt.seeded_load(module).await.expect("seeded load"),
        1,
        "fixture must load"
    );

    // The Rust side is an out-of-runtime peer (the "another process" shape):
    // it opens every connection while the fixture's JS thread is blocked, then
    // releases the fixture and reads all responses.
    //
    // The two sides MUST run concurrently: the fixture publishes its port and
    // then blocks until the peer writes the go flag, while the peer waits for
    // that port — awaiting the peer BEFORE the emit deadlocks both (the
    // fixture's handler runs inside the emit).
    let peer_dir = dir.clone();
    let peer = tokio::task::spawn_blocking(move || {
        use std::io::{Read, Write};
        use std::net::TcpStream;

        let port_file = peer_dir.join("port.txt");
        let go_file = peer_dir.join("go.txt");
        let port = {
            let deadline = std::time::Instant::now() + std::time::Duration::from_secs(10);
            loop {
                if let Ok(text) = std::fs::read_to_string(&port_file) {
                    if let Ok(port) = text.trim().parse::<u16>() {
                        break port;
                    }
                }
                assert!(
                    std::time::Instant::now() < deadline,
                    "fixture never published its listening port"
                );
                std::thread::sleep(std::time::Duration::from_millis(10));
            }
        };
        // Connect + send every request first (the listener's backlog drains on
        // its own accept thread, so a connect rarely needs a retry).
        let mut streams = Vec::with_capacity(SERVER_BOUND_REQUESTS);
        for index in 0..SERVER_BOUND_REQUESTS {
            let mut attempt = 0;
            let stream = loop {
                match TcpStream::connect(("127.0.0.1", port)) {
                    Ok(stream) => break stream,
                    Err(error) => {
                        attempt += 1;
                        assert!(attempt < 20, "connect {index} failed: {error}");
                        std::thread::sleep(std::time::Duration::from_millis(20));
                    }
                }
            };
            let _ = stream.set_read_timeout(Some(std::time::Duration::from_secs(60)));
            streams.push(stream);
        }
        for (index, stream) in streams.iter_mut().enumerate() {
            let request =
                format!("GET /r{index} HTTP/1.1\r\nhost: 127.0.0.1\r\nconnection: close\r\n\r\n");
            stream.write_all(request.as_bytes()).expect("write request");
            stream.flush().expect("flush request");
        }
        // Release the fixture's JS thread: its pump resumes and answers.
        std::fs::write(&go_file, b"go").expect("write go flag");

        let mut answered = 0usize;
        let mut wrong = 0usize;
        for (index, stream) in streams.iter_mut().enumerate() {
            let mut response = Vec::new();
            stream.read_to_end(&mut response).expect("read response");
            let text = String::from_utf8_lossy(&response);
            answered += 1;
            if !text.starts_with("HTTP/1.1 200") || !text.ends_with(&format!("path:/r{index}")) {
                wrong += 1;
            }
        }
        (answered, wrong)
    });

    // Drive both: the emit's first poll starts the fixture (it publishes the
    // port and then blocks on the go flag), the peer connects + sends + writes
    // the flag + reads the responses.
    let mut payload = json!({ "reason": "startup" });
    let emit = rt.emit("session_start", &mut payload);
    let (outcome, peer) = tokio::join!(emit, peer);
    let outcome = outcome.expect("emit session_start");
    let peer = peer.expect("peer task");
    assert!(
        outcome.errors.is_empty(),
        "handler errors: {:?}",
        outcome.errors
    );
    let report: Value = rt
        .eval_json("JSON.stringify(globalThis.__pirPaced)")
        .await
        .expect("read fixture report");

    assert_eq!(
        report["handled"].as_u64(),
        Some(SERVER_BOUND_REQUESTS as u64),
        "every request is dispatched exactly once past the bound: {report}"
    );
    assert_eq!(
        report["unique"].as_u64(),
        Some(SERVER_BOUND_REQUESTS as u64),
        "no duplicate dispatch: {report}"
    );
    assert_eq!(
        peer.0, SERVER_BOUND_REQUESTS,
        "every client received a response: {peer:?}"
    );
    assert_eq!(
        peer.1, 0,
        "every response answered its own request: {peer:?}"
    );
    let _ = std::fs::remove_dir_all(&dir);
}
