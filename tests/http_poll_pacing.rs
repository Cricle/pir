//! `node:http` poll-loop pacing: loopback latency and streaming delivery.
//!
//! The client's poll loops used to re-arm on timers (`setTimeout(..., 10)` /
//! `(..., 5)`), and this runtime's event-loop drain advances timers on a
//! ~10 ms beat, so a loopback request cost ~100 ms. Two independent costs are
//! pinned here:
//!
//!   * a same-process `http.Server` is stepped by the client's poll loop
//!     (`http_shim.js.txt`'s local pump), so the in-process round trip needs
//!     no timer hop at all — `loopback_ten_sequential_requests_are_fast`;
//!   * the server's accept loop probes a non-blocking listener, and its sleep
//!     is the connect latency a loopback client pays (`http_fns.rs`'s 1 ms
//!     accept step) — a fresh connection per request is the worst case, and
//!     the in-process test above uses one per request.
//!
//! Fixtures are generated at runtime into per-test temp dirs (repository
//! hygiene gate; same pattern as `tests/http_shims.rs`).

use std::io::{Read, Write};
use std::net::{TcpListener, TcpStream};
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;

use pir::extensions::{ExtensionConfig, ExtensionRuntime};
use serde_json::{json, Value};

/// See tests/extensions_runtime.rs: fixtures must be written at runtime.
fn write_temp_fixture(test_name: &str, files: &[(&str, &str)]) -> PathBuf {
    let dir =
        std::env::temp_dir().join(format!("pir-http-paced-{}-{test_name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create fixture dir");
    for (name, content) in files {
        let path = dir.join(name);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).expect("create fixture subdir");
        }
        std::fs::write(&path, content).expect("write fixture");
    }
    dir
}

fn test_config() -> ExtensionConfig {
    ExtensionConfig {
        cwd: std::env::temp_dir(),
        mode: "headless".to_string(),
        has_ui: false,
        model: Some("test-model".to_string()),
        session_id: Some("test-session".to_string()),
        system_prompt: "You are a test.".to_string(),
        is_idle: true,
        limits: Some(Default::default()),
    }
}

async fn run_fixture(rt: &ExtensionRuntime, name: &str, ts: &str, global: &str) -> Value {
    let module = format!("pir-ext:{name}.ts");
    rt.seed_module(&module, ts).expect("seed fixture");
    let loaded = rt.seeded_load(&module).await;
    assert_eq!(loaded.expect("seeded load"), 1, "fixture {name} must load");
    let mut payload = json!({ "reason": "startup" });
    let outcome = match rt.emit("session_start", &mut payload).await {
        Ok(outcome) => outcome,
        Err(error) => {
            // A fixture that stalls has to name WHERE it stalled: every
            // fixture publishes `globalThis.__pirPaced` before it waits, and
            // the host recovers the runtime after an engine-level abort, so
            // the last recorded phase stays readable here. Without this the
            // only report is rquickjs's opaque "Exception generated by
            // QuickJS".
            let progress = rt
                .eval_json("JSON.stringify(globalThis.__pirPaced ?? null)")
                .await
                .map(|value| value.to_string())
                .unwrap_or_else(|error| format!("<unreadable: {error}>"));
            panic!(
                "emit session_start failed for fixture {name}: {error}; fixture progress: {progress}"
            );
        }
    };
    assert!(
        outcome.errors.is_empty(),
        "handler errors in {name}: {:?}",
        outcome.errors
    );
    rt.eval_json(&format!("JSON.stringify(globalThis.{global})"))
        .await
        .expect("read fixture results")
}

async fn run_pacing_fixture(name: &str, body: &str) -> Value {
    let dir = write_temp_fixture(name, &[("index.ts", body)]);
    let rt = ExtensionRuntime::new(test_config()).await.expect("runtime");
    rt.allow_root(dir);
    run_fixture(&rt, name, body, "__pirPaced").await
}

/// The client half every fixture shares: `count` sequential GETs, each fully
/// drained, reporting the wall time and the bodies.
const CLIENT_HELPERS: &str = r#"
import http from "node:http";

function nowMs() {
  const perf = globalThis.performance;
  if (perf && typeof perf.now === "function") return perf.now();
  return Date.now();
}

function getSequence(port, count) {
  return (async function () {
    const started = nowMs();
    const bodies = [];
    const perRequestMs = [];
    for (let i = 0; i < count; i++) {
      const at = nowMs();
      bodies.push(await new Promise(function (resolve, reject) {
        const request = http.get("http://127.0.0.1:" + port + "/seq?i=" + i, function (res) {
          let body = "";
          res.on("data", function (chunk) { body += chunk.toString("utf8"); });
          res.on("end", function () { resolve(body); });
        });
        request.on("error", function (error) { reject(error); });
      }));
      perRequestMs.push(nowMs() - at);
    }
    return { totalMs: nowMs() - started, perRequestMs: perRequestMs, bodies: bodies };
  })();
}
"#;

/// Ten sequential requests against a server inside the same runtime: the shape
/// the pacing was built for. Before the pacing/accept work this took ~1 s
/// (each request paid a blocking poll that starved the server, then ~10 ms
/// timer hops); it is a handful of milliseconds now. The bound is deliberately
/// loose — an order of magnitude over the observed value — so a loaded CI box
/// cannot flake it, while a regression to timer-hop pacing fails it.
#[tokio::test(flavor = "current_thread")]
async fn loopback_ten_sequential_requests_are_fast() {
    let ts = format!(
        r#"{CLIENT_HELPERS}
export default (pi) => {{
  pi.on("session_start", async () => {{
    const server = http.createServer(function (_req, res) {{
      res.writeHead(200, {{ "content-type": "text/plain" }});
      res.end("pong");
    }});
    await new Promise(function (resolve) {{ server.listen(0, resolve); }});
    const out = await getSequence(server.address().port, 10);
    server.close();
    globalThis.__pirPaced = out;
  }});
}};
"#
    );
    let v = run_pacing_fixture("in-process", &ts).await;

    let total = v["totalMs"].as_f64().expect("totalMs");
    let bodies = v["bodies"].as_array().expect("bodies");
    assert_eq!(bodies.len(), 10, "every request answered: {v}");
    assert!(
        bodies.iter().all(|body| body == "pong"),
        "every response body round tripped: {v}"
    );
    println!(
        "in-process loopback: {total:.1} ms for 10 requests, per request {:?}",
        v["perRequestMs"]
    );
    assert!(
        total < 600.0,
        "10 in-process loopback requests must not pay timer-hop pacing (took {total} ms): {v}"
    );
}

/// Canned HTTP/1.1 server on a Rust thread: reads one request head per
/// connection and answers with `response`. The peer is therefore outside the
/// JS runtime — the "another process" shape.
fn spawn_canned_server(response: &'static str) -> u16 {
    let listener = TcpListener::bind("127.0.0.1:0").expect("bind loopback");
    let port = listener.local_addr().expect("local addr").port();
    std::thread::spawn(move || {
        for stream in listener.incoming().flatten() {
            let mut stream = stream;
            let mut buffer = [0u8; 4096];
            let _ = stream.read(&mut buffer);
            let _ = stream.write_all(response.as_bytes());
            let _ = stream.flush();
        }
    });
    port
}

